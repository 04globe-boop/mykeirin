"""選手の談話（コメント）から、調子についての発言を取り出す手作りの辞書。

2026-10-20 に、成績を見る前に作成して固定した（mykeirin2/research/p9b_danwa_design.md）。
並びの宣言（「自力」「〇〇君」）は調子の情報ではないので、何も当たらない。

返す値（どれも 0/1。1つの談話に複数当たることがある）
  pos    調子が良い・上向き（良い、悪くない、戻ってきた、疲労が抜けた、感触はいい など）
  neg    調子が悪い・不安（重い、疲労、きつい、出が悪い、痛い、不安、噛み合わない など）
  equip  機材を変えた・調整した（新車、フレーム、セッティング、ハンドル、ギヤ など）
  train  練習・調整の話（練習、調整、仕上げ、追い込み など）
  hurt   けが・落車・体の痛み（痛、腰、膝、怪我、落車明け など）。neg にも含める
"""
from __future__ import annotations

import re

# 否定で意味が反転する言い方を、先に「良い」側として処理する
POS_FIRST = r"悪くは(な|無)|悪く無|悪くな|疲労が抜け|疲れが抜け|疲労は抜け|疲れは抜け|重くな|痛みはな|痛くな|不安はな|問題な|心配な"
POS = r"良い|良かった|良く|いい感じ|感じがいい|感じはいい|感触はいい|感触が良|調子はいい|調子が良|上向|戻って|戻り|仕上が|手応え|軽い|軽かった|軽く|動いて|余裕|しっくり|好感触|状態は良|状態がいい|進んで"
NEG = r"悪い|悪かった|悪く|重い|重かった|重た|重く|疲れ|疲労|きつ|しんど|出が悪|脚がな|脚が重|痛|腰|膝|怪我|ケガ|落車明け|落車の影響|不安|イマイチ|いまいち|今一つ|ダメ|駄目|物足りな|噛み合|合わな|休み明け|欠場明け|空回り|バラバラ|微妙"
EQUIP = r"新車|フレーム|セッティング|ハンドル|サドル|ギヤ|ギア|部品|車輪|ペダル|機材|ポジション|自転車を"
TRAIN = r"練習|調整|仕上げ|追い込|合宿|乗り込"
HURT = r"痛|腰|膝|怪我|ケガ|落車明け|落車の影響|骨折|鎖骨|擦過"

_pf, _p, _n, _e, _t, _h = (re.compile(x) for x in (POS_FIRST, POS, NEG, EQUIP, TRAIN, HURT))


def tag(text: str) -> dict[str, int]:
    t = (text or "").replace(" ", "").replace("　", "")
    pos_first = bool(_pf.search(t))
    t_wo = _pf.sub("", t)  # 「悪くない」などを取り除いてから悪い側を見る
    return {
        "pos": int(pos_first or bool(_p.search(t_wo))),
        "neg": int(bool(_n.search(t_wo))),
        "equip": int(bool(_e.search(t))),
        "train": int(bool(_t.search(t))),
        "hurt": int(bool(_h.search(t_wo))),
        "len": len(t),
    }
